--   installation_hash TEXT       PK, SHA-256 của UUID localStorage
--   origin            TEXT       ustudy.hakhoi.io.vn | ustudy.unopia.io.vn
--   first_seen_day    TEXT       ngày đầu hoạt động, YYYY-MM-DD
