--
-- installation_activity_days: một dòng cho mỗi installation mỗi ngày hoạt động
--   installation_hash TEXT       FK -> anonymous_installations.installation_hash
--   active_day        TEXT       ngày hoạt động, YYYY-MM-DD
--   PRIMARY KEY (installation_hash, active_day)
